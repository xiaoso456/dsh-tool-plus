/* -------------------------------------------------------------------------- */
/* Format / hash helpers (verbatim upstream shims onto the native engine)      */
/* -------------------------------------------------------------------------- */

/** `[path#TAG]` section header. */
export function formatHashlineHeader(path: string, tag: string): string {
	return hashlineFormatHeader(path, tag);
}

/** `N:line` numbered display rows starting at `startLine` (default 1). */
export function formatNumberedLines(text: string, startLine?: number): string {
	return hashlineFormatNumberedLines(text, startLine);
}

/**
 * One `N:line` display row. Composed in TS rather than delegated: the native
 * surface has no single-line formatter (`hashlineFormatNumberedLines` takes a
 * whole text), and the JS join is byte-identical to the native row shape —
 * upstream composes it the same way (hashline-format.ts:26-28).
 */
export function formatNumberedLine(lineNumber: number, line: string): string {
	return `${lineNumber}:${line}`;
}

/**
 * Split `text` into addressable rows, dropping the empty row a trailing
 * newline produces. Upstream hashline-format.ts:30-34; the native engine
 * numbers the same way internally.
 */
export function splitAddressableFileLines(text: string): string[] {
	const lines = text.split("\n");
	if (lines.at(-1) === "") lines.pop();
	return lines;
}

/** Strip hashline display prefixes (`N:` / `+N:` …) from pasted rows. */
export function stripHashlinePrefixes(lines: string[]): string[] {
	return hashlineStripPrefixes(lines);
}

/** 4-hex hashline content tag for `text`. */
export function computeFileHash(text: string): string {
	return hashlineFileHash(text);
}

/* -------------------------------------------------------------------------- */
/* Session store (verbatim upstream edit/store.ts)                             */
/* -------------------------------------------------------------------------- */

/** Owner of the lazily created per-session store. */
export interface EditStoreOwner {
	editStore?: EditStore;
}

/**
 * The session's store, created on first use (verbatim upstream
 * `edit/store.ts:15-18`).
 *
 * One store per session carries the full-file snapshots that mint hashline
 * tags, the `CUT`/`PUT` clipboard registers, and the byte-identical no-op loop
 * guard — every {@link EditSession} the edit tool opens shares it, and the
 * read/search/write tools mint their tags into it.
 *
 * DSH note: DSH rebuilds its `ToolSession` object on every tool call and
 * round-trips the store through `shared/session-state.ts`, so the engine path
 * reaches the store through `getFileSnapshotStore` in
 * `src/tools/omp/edit/file-snapshot-store.ts`, which delegates here.
 */
export function getEditStore(session: EditStoreOwner): EditStore {
	session.editStore ??= new EditStore();
	return session.editStore;
}

/* -------------------------------------------------------------------------- */
/* DSH error type for native rejections                                        */
/* -------------------------------------------------------------------------- */

/**
 * Raised when the native engine rejects a payload.
 *
 * The Rust engine reports every rejection as an `isError` outcome carrying the
 * model-facing text — mismatched tag, unseen anchor line, missing file, no-op
 * escalation (upstream `edit/index.ts:495-497` returns it as a tool result).
 * DSH's `edit` tool contract is throw-based (`toText` in
 * `src/tools/edit/adapter/index.ts` throws when a result is `isError`), and
 * DSH's per-file detail shape carries `displayErrorText` sourced from
 * `MismatchError.displayMessage` (`details.ts`, `dispatch.ts`), so
 * `executeHashlineSingle` re-raises the native text as this class. Both
 * `message` and `displayMessage` are exactly the native text, so the model
 * sees the teaching message unchanged.
 *
 * (Upstream's pre-18.0 `MismatchError` formatted its own richer diagnostic
 * from structured fields; the native text already contains that diagnostic,
 * hence the single-string shape.)
 */
export class MismatchError extends Error {
	/** Model/TUI-facing text — always identical to {@link Error.message}. */
	readonly displayMessage: string;

	constructor(message: string) {
		super(message);
		this.name = "MismatchError";
		this.displayMessage = message;
	}
}

