/**
 * DSH adapter for the native (Rust) hashline engine.
 *
 * Upstream deleted the TypeScript `@oh-my-pi/hashline` package in 18.x and
 * rewrote the engine as `crates/pi-edit/src/modes/hashline/*.rs`, exposed
 * through `@oh-my-pi/pi-natives`. This module is the single seam DSH keeps
 * against it, and it is a **verbatim port** of the two upstream TS files that
 * replaced the old engine surface:
 *
 * - `refs/oh-my-pi/packages/coding-agent/src/tools/hashline-format.ts` (41L)
 *   → the `HL_*` constants plus the format/hash helpers below.
 * - `refs/oh-my-pi/packages/coding-agent/src/edit/store.ts` (19L)
 *   → {@link getEditStore}.
 *
 * The multi-mode transport (`Patcher`/`Filesystem`/`Clipboard`/`InMemorySnapshotStore`)
 * is gone on purpose: `EditSession.apply` owns staging, snapshot validation,
 * `N*` block resolution, clipboard registers, the no-op loop guard, and the
 * model-facing text. Hosts only supply an {@link EditPolicy} and a writer
 * callback — see `./policy.ts` and `./writer.ts`.
 *
 * `tsconfig.json` aliases `@oh-my-pi/hashline` onto this module, so the DSH
 * tools that only need the display/format helpers (read / write / grep /
 * ast-edit / ast-grep / plan-mode-guard) import it directly.
 */
