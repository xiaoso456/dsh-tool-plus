describe("adapter session lifecycle", () => {
	it("applies a payload and reports the landed bytes", async () => {
		const { dir, store } = makeCase("session-apply");
		const abs = path.join(dir, "a.ts");
		fs.writeFileSync(abs, "alpha\nbeta\n");
		const tag = store.recordSnapshot(abs, "alpha\nbeta\n");

		const outcome = await applyInput(store, dir, `[a.ts#${tag}]\nPUT 2.=2:\n+BETA`);
		expect(outcome.isError).toBe(false);
		expect(outcome.text).toContain("[a.ts#");
		expect(outcome.files).toHaveLength(1);
		expect(fs.readFileSync(abs, "utf8")).toBe("alpha\nBETA\n");
	});

	it("reports a rejected payload as an outcome instead of throwing", async () => {
		const { dir, store } = makeCase("session-reject");
		const abs = path.join(dir, "a.ts");
		fs.writeFileSync(abs, "alpha\nbeta\n");
		store.recordSnapshot(abs, "alpha\nbeta\n");

		const outcome = await applyInput(store, dir, "[a.ts#FFFF]\nPUT 1.=1:\n+x");
		expect(outcome.isError).toBe(true);
		expect(outcome.text).toContain("is not from this session");
		expect(fs.readFileSync(abs, "utf8")).toBe("alpha\nbeta\n");
	});
});

