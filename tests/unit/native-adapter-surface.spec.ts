/**
 * Native adapter surface — compat-layer coverage.
 *
 * `src/tools/hashline/native/index.ts` is the seam between DSH and the Rust
 * `@oh-my-pi/pi-natives` bindings: it re-exports the native transport, keeps
 * the deleted TS engine's display helpers and line-ending/BOM ports, and owns
 * the session store accessor plus the throw-based `MismatchError`. The migrated
 * engine suites under `src/tools/hashline/test/**` exercise that seam
 * behaviourally; this spec pins the **surface itself** — every runtime export
 * is callable and returns its documented observable result, so a renamed,
 * dropped or silently degraded re-export cannot hide behind the engine suites.
 *
 * Contract under test:
 *  - `HL_*` constants and the format helpers (`formatHashlineHeader`,
 *    `formatNumberedLines`, `formatNumberedLine`, `splitAddressableFileLines`,
 *    `stripHashlinePrefixes`, `computeFileHash`)
 *  - `getEditStore` (lazy creation + memoization on the owner object) and
 *    `MismatchError` (`message === displayMessage`, `name`, `instanceof Error`)
 *  - every native re-export: `blockRangeAt`, `buildCompactDiffPreview`,
 *    `detectLineEnding`, `normalizeToLF`, `restoreLineEndings`, `stripBom`,
 *    `editAutoGeneratedMessage`, `editDescription`, `editDiffString`,
 *    `editGrammar`, `editInspect`, `hashlineCountOps`, `structuredPatchHunks`,
 *    `EditStore` (full method set), `EditSession` (apply + rejection lifecycle)
 *  - the vendored fixture corpus driven through a real `EditStore` +
 *    `EditSession`: every payload-bearing case must COMPLETE through the
 *    adapter (an engine rejection is a legitimate completion; a throw is not),
 *    and the unreachable cases are enumerated with their reason.
 *
 * Deliberately not a duplicate of `src/tools/hashline/test/hashline-fixtures.test.ts`:
 * that spec asserts the fixtures' exact expected bytes; this one asserts the
 * compat-layer call itself works and reports the reachable boundary.
 */
