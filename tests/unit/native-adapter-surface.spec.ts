const RAW_ROOT = fs.mkdtempSync(path.join(os.tmpdir(), "native-adapter-surface-"));
const ROOT = fs.realpathSync.native(RAW_ROOT);
const FIXTURE_DIR = fileURLToPath(new URL("../../src/tools/hashline/test/fixtures", import.meta.url));

let caseSeq = 0;

/** One case's real on-disk directory plus an isolated store. */
function makeCase(label: string): { dir: string; store: EditStore } {
	const dir = path.join(ROOT, `${String(caseSeq++).padStart(3, "0")}-${label.replace(/[^A-Za-z0-9._-]+/g, "_").slice(0, 40)}`);
	fs.mkdirSync(dir, { recursive: true });
	return { dir, store: new EditStore() };
}

function policyFor(cwd: string, overrides: Partial<EditPolicy> = {}): EditPolicy {
	return {
		cwd,
		mode: "hashline",
		allowFuzzy: true,
		fuzzyThreshold: 0.95,
		enforceSeenLines: false,
		blockAutoGenerated: true,
		planActive: false,
		homeDir: cwd,
		rawInput: false,
		...overrides,
	};
}

/** Disk-backed writer: `delete` unlinks, `move` writes+unlinks, else writes. */
function diskWriter(): { requests: EditWriteRequest[]; fn: (error: Error | null, request: EditWriteRequest) => Promise<EditWriteResponse> } {
	const requests: EditWriteRequest[] = [];
	const fn = async (error: Error | null, request: EditWriteRequest): Promise<EditWriteResponse> => {
		if (error) throw error;
		requests.push(request);
		if (request.op === "delete") {
			fs.rmSync(request.path, { force: true });
			return { written: "" };
		}
		const text = request.content ?? "";
		const target = request.moveTo ?? request.path;
		fs.mkdirSync(path.dirname(target), { recursive: true });
		fs.writeFileSync(target, text, "utf8");
		if (request.moveTo) fs.rmSync(request.path, { force: true });
		return { written: text };
	};
	return { requests, fn };
}

/** Drive one payload through the adapter's session lifecycle. */
async function applyInput(
	store: EditStore,
	cwd: string,
	input: string,
	policy: Partial<EditPolicy> = {},
): Promise<{ text: string; isError: boolean; files: unknown[] }> {
	const writer = diskWriter();
	const session = new EditSession(store, policyFor(cwd, policy), null);
	try {
		session.setArgsJson(JSON.stringify({ input }));
		session.finish();
		return (await session.apply({ lspFlush: false }, writer.fn)) as { text: string; isError: boolean; files: unknown[] };
	} finally {
		session.close();
	}
}

afterAll(() => {
	fs.rmSync(RAW_ROOT, { recursive: true, force: true });
});

