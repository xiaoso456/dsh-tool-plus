describe("adapter session store and error type", () => {
	it("creates the store lazily and memoizes it on the owner object", () => {
		const owner: { editStore?: EditStore } = {};
		expect(owner.editStore).toBeUndefined();
		const first = getEditStore(owner);
		expect(first).toBeInstanceOf(EditStore);
		expect(owner.editStore).toBe(first);
		expect(getEditStore(owner)).toBe(first);
		expect(getEditStore({})).not.toBe(first);
	});

	it("drives every EditStore accessor through one path's lifecycle", () => {
		const { dir, store } = makeCase("store-lifecycle");
		const abs = path.join(dir, "demo.ts");
		const text = "function f() {\n  const a = 1;\n}\n";
		fs.writeFileSync(abs, text);

		const tag = store.recordSnapshot(abs, text, [1, 2]);
		expect(tag).toBe(computeFileHash(text));
		expect(store.headHash(abs)).toBe(tag);
		expect(store.headText(abs)).toBe(text);
		expect(store.byHashText(abs, tag)).toBe(text);
		expect(store.byHashText(abs, "0000")).toBeNull();
		expect(store.seenLines(abs, tag)).toEqual([1, 2]);
		expect(store.seenLines(abs, "0000")).toBeNull();

		const moved = path.join(dir, "moved.ts");
		store.relocate(abs, moved);
		expect(store.byHashText(moved, tag)).toBe(text);
		expect(store.byHashText(abs, tag)).toBeNull();

		store.invalidate(moved);
		expect(store.headHash(moved)).toBeNull();

		store.recordSnapshot(moved, text);
		store.clear();
		expect(store.headHash(moved)).toBeNull();
		expect(store.byHashText(moved, tag)).toBeNull();
	});

	it("carries the native rejection text through MismatchError unchanged", () => {
		const error = new MismatchError("Edit rejected for a.ts: hash #FFFF is not from this session.");
		expect(error).toBeInstanceOf(Error);
		expect(error).toBeInstanceOf(MismatchError);
		expect(error.name).toBe("MismatchError");
		expect(error.message).toBe("Edit rejected for a.ts: hash #FFFF is not from this session.");
		expect(error.displayMessage).toBe(error.message);
	});
});

